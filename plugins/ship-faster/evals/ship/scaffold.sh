#!/usr/bin/env bash
set -euo pipefail
git init -q -b main .
git config user.email eval@example.com
git config user.name eval
mkdir -p src docs/wiki
cat > package.json <<'EOF'
{ "name": "greeter", "version": "1.0.0", "type": "module", "scripts": { "test": "node --test" } }
EOF
cat > .gitignore <<'EOF'
node_modules/
scaffold.sh
.bash_profile
.bashrc
.claude
.eval-artifacts
.gitconfig
.gitmodules
.idea
.mcp.json
.profile
.ripgreprc
.vscode
.zprofile
.zshrc
EOF
cat > src/greet.js <<'EOF'
export function greet(name) { return `Hello, ${name}`; }
EOF
cat > greet.test.js <<'EOF'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { greet } from './src/greet.js';
test('greets', () => { assert.equal(greet('Ada'), 'Hello, Ada'); });
EOF
cat > docs/wiki/commands.md <<'EOF'
---
title: Commands
summary: Verified test command.
read_when: You need to run the tests.
covers: ["package.json"]
verified: unverified
updated: 2026-01-01
checks:
  - name: test
    run: node --test
    timeout: 120
---
# Commands

## Setup
| Step | Command | Notes |
|---|---|---|
| Install | `npm install` | no dependencies |

## Everyday
| Purpose | Command | Duration | Status |
|---|---|---|---|
| Tests | `node --test` | 1s | pass |

## Checks
1. `node --test`

## Known slow or flaky
- none
EOF
cat > docs/wiki/conventions.md <<'EOF'
---
title: Conventions
summary: Small rules for this library.
read_when: You are changing src/.
covers: ["src/**"]
verified: unverified
updated: 2026-01-01
---
# Conventions

## Follow
- Export named functions only; no default exports. Example: `src/greet.js:1`

## Avoid
- Template literals with logic inside them; compute the value first.

## Style
| Aspect | Rule | Enforced by |
|---|---|---|
| exports | named | review |
EOF
cat > docs/wiki/index.md <<'EOF'
<!-- Generated by ship-faster. Do not edit: run /ship-faster:sync-docs to regenerate. -->
# Wiki index

| Page | Read when | Summary |
|---|---|---|
| [Commands](commands.md) | You need to run the tests. | Verified test command. |
| [Conventions](conventions.md) | You are changing src/. | Small rules for this library. |
EOF
git add package.json .gitignore src/greet.js greet.test.js docs/wiki
git commit -q -m "feat: greeter with docs"
sha=$(git rev-parse HEAD)
sed -i "s/^verified: unverified$/verified: $sha/" docs/wiki/commands.md docs/wiki/conventions.md
git add docs/wiki/commands.md docs/wiki/conventions.md
git commit -q -m "docs: verify pages"
git checkout -q -b feat/farewell
cat > src/farewell.js <<'EOF'
export function farewell(name) { return `Goodbye, ${name}`; }
EOF
cat > farewell.test.js <<'EOF'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { farewell } from './src/farewell.js';
test('says goodbye', () => { assert.equal(farewell('Ada'), 'Goodbye, Ada'); });
EOF
git add src/farewell.js farewell.test.js
git commit -q -m "feat: farewell"
cat > src/greet.js <<'EOF'
export function greet(name) { return `Hello, ${name}!`; }
EOF
cat > greet.test.js <<'EOF'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { greet } from './src/greet.js';
test('greets', () => { assert.equal(greet('Ada'), 'Hello, Ada!'); });
EOF
