# Gotchas

### Plain console.log breaks log shipping <!-- id: g-20260101-console-log -->
Symptom: the log collector drops lines and alerts on "unparseable log line".
Cause: the collector expects one JSON object per line; console.log writes plain text without the request id.
Rule: Never call console.log under src/; use log() from src/lib/log.js.
Evidence: src/lib/log.js:1, 2026-01-01.
