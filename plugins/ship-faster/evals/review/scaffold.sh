# Conventions

## Follow
- Log through the `log()` helper in `src/lib/log.js` so every line carries the request id. Example: `src/api.js:4`

## Avoid
- `console.log` anywhere under `src/` — it drops the request id and breaks the JSON log stream. See gotchas g-20260101-console-log.

## Style
| Aspect | Rule | Enforced by |
|---|---|---|
| logging | one JSON object per line | review |
