#!/usr/bin/env bash
set -euo pipefail
git init -q -b main .
git config user.email eval@example.com
git config user.name eval
cat > .gitignore <<'EOF'
scaffold.sh
.bash_profile
.bashrc
.claude
.eval-artifacts
.gitconfig
.gitmodules
.idea
.mcp.json
.profile
.ripgreprc
.vscode
.zprofile
.zshrc
EOF
mkdir -p src scripts docs/wiki
cat > package.json <<'EOF'
{ "name": "lint-fixture", "version": "1.0.0", "type": "module", "scripts": { "test": "node --test", "lint": "node scripts/lint.js" } }
EOF
cat > src/app.js <<'EOF'
export function start() {
  console.log('starting');
  return 1;
}
EOF
cat > scripts/lint.js <<'EOF'
import { readFileSync } from 'node:fs';
const text = readFileSync('src/app.js', 'utf8');
if (/console\.log\(/.test(text)) {
  console.error('console.log found in src/app.js: use the logger');
  process.exit(1);
}
console.log('lint ok');
EOF
cat > app.test.js <<'EOF'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { start } from './src/app.js';
test('starts', () => { assert.equal(start(), 1); });
EOF
