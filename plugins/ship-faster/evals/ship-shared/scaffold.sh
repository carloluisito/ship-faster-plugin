#!/usr/bin/env bash
set -euo pipefail
export GIT_AUTHOR_DATE="2026-01-01T00:00:00Z" GIT_COMMITTER_DATE="2026-01-01T00:00:00Z"
git init -q -b main .
git config user.email eval@example.com
git config user.name eval
mkdir -p src docs/wiki
cat > .gitignore <<'EOF'
node_modules/
scaffold.sh
.bash_profile
.bashrc
.claude
.eval-artifacts
.gitconfig
.gitmodules
.idea
.mcp.json
.profile
.ripgreprc
.vscode
.zprofile
.zshrc
EOF
cat > package.json <<'EOF'
{ "name": "greeter", "version": "1.0.0", "type": "module", "scripts": { "test": "node --test" } }
EOF
cat > README.md <<'EOF'
# greeter

Exports `greet(name)` from `src/greet.js`.
EOF
cat > src/greet.js <<'EOF'
export function greet(name) { return `Hello, ${name}`; }
EOF
cat > greet.test.js <<'EOF'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { greet } from './src/greet.js';
test('greets', () => { assert.equal(greet('Ada'), 'Hello, Ada'); });
EOF
cat > docs/wiki/commands.md <<'EOF'
---
title: Commands
summary: Verified test command.
read_when: You need to run the tests.
covers: ["package.json"]
verified: unverified
updated: 2026-01-01
checks:
  - name: test
    run: node --test
    timeout: 120
---
# Commands

## Setup
| Step | Command | Notes |
|---|---|---|
| Install | none | no dependencies |

## Everyday
| Purpose | Command | Duration | Status |
|---|---|---|---|
| Tests | `node --test` | 1s | pass |

## Checks
1. `node --test`

## Known slow or flaky
- none
EOF
cat > docs/wiki/index.md <<'EOF'
<!-- Generated by ship-faster. Do not edit: run /ship-faster:sync-docs to regenerate. -->
# Wiki index

| Page | Read when | Summary |
|---|---|---|
| [Commands](commands.md) | You need to run the tests. | Verified test command. |
EOF
git add .gitignore package.json README.md src/greet.js greet.test.js docs/wiki
git commit -q -m "feat: greeter"
sha=$(git rev-parse HEAD)
sed -i "s/^verified: unverified$/verified: $sha/" docs/wiki/commands.md
git add docs/wiki/commands.md
git commit -q -m "docs: verify commands"

# This session's ticket: a farewell function, its test, and a README line.
cat > src/farewell.js <<'EOF'
export function farewell(name) { return `Goodbye, ${name}`; }
EOF
cat > farewell.test.js <<'EOF'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { farewell } from './src/farewell.js';
test('says goodbye', () => { assert.equal(farewell('Ada'), 'Goodbye, Ada'); });
EOF
cat >> README.md <<'EOF'
Exports `farewell(name)` from `src/farewell.js`.
EOF

# Another open session's unfinished work in the same checkout.
cat > src/greet.js <<'EOF'
export function greet(name) { return `Hello, ${name}`; }
export function shout(name) { return greet(name).toUpperCase(); }
EOF

# Record the other session as open in this checkout and as the editor of src/greet.js.
state=.git/ship-faster
mkdir -p "$state/sessions" "$state/edits"
now="$(date -u +%Y-%m-%dT%H:%M:%S.000Z)"
printf '{"startedAt":"%s","updatedAt":"%s","branch":"main","cwd":"%s","pages":{}}\n' "$now" "$now" "$(pwd -P)" > "$state/sessions/other-session.json"
printf '{"sid":"other-session","updatedAt":"%s","files":{"src/greet.js":{"at":"%s","tool":"Edit"}}}\n' "$now" "$now" > "$state/edits/other-session.json"
