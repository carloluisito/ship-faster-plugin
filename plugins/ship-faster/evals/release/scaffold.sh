#!/usr/bin/env bash
set -euo pipefail
git init -q -b main .
git config user.email eval@example.com
git config user.name eval
mkdir -p src docs/wiki
cat > .gitignore <<'EOF'
node_modules/
scaffold.sh
.bash_profile
.bashrc
.claude
.eval-artifacts
.gitconfig
.gitmodules
.idea
.mcp.json
.profile
.ripgreprc
.vscode
.zprofile
.zshrc
EOF
cat > package.json <<'EOF'
{
  "name": "counter",
  "version": "1.0.0",
  "type": "module",
  "scripts": { "test": "node --test" }
}
EOF
cat > src/counter.js <<'EOF'
export function count(items) { return items.length; }
EOF
cat > counter.test.js <<'EOF'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { count } from './src/counter.js';
test('counts', () => { assert.equal(count([1, 2]), 2); });
EOF
cat > docs/wiki/commands.md <<'EOF'
---
title: Commands
summary: Verified test command.
read_when: You need to run the tests.
covers: ["package.json"]
verified: unverified
updated: 2026-01-01
checks:
  - name: test
    run: node --test
    timeout: 120
---
# Commands

## Setup
| Step | Command | Notes |
|---|---|---|
| Install | `npm install` | no dependencies |

## Everyday
| Purpose | Command | Duration | Status |
|---|---|---|---|
| Tests | `node --test` | 1s | pass |

## Checks
1. `node --test`

## Known slow or flaky
- none
EOF
cat > docs/wiki/ops.md <<'EOF'
---
title: Ops
summary: How counter is versioned and released.
read_when: You are cutting a release or need the current version.
covers: ["package.json"]
verified: unverified
updated: 2026-01-01
---
# Ops

## Release
- The first release, v1.0.0, was tagged on `main`.
- Current version: 1.0.0, set in `package.json`.
- Releases are annotated tags named `vX.Y.Z`.
EOF
cat > docs/wiki/index.md <<'EOF'
<!-- Generated by ship-faster. Do not edit: run /ship-faster:sync-docs to regenerate. -->
# Wiki index

| Page | Read when | Summary |
|---|---|---|
| [Commands](commands.md) | You need to run the tests. | Verified test command. |
| [Ops](ops.md) | You are cutting a release or need the current version. | How counter is versioned and released. |
EOF
git add .gitignore package.json src/counter.js counter.test.js docs/wiki
git commit -q -m "feat: counter"
sha=$(git rev-parse HEAD)
sed -i "s/^verified: unverified$/verified: $sha/" docs/wiki/commands.md docs/wiki/ops.md
git add docs/wiki/commands.md docs/wiki/ops.md
git commit -q -m "docs: verify commands and ops"
git tag -a v1.0.0 -m "v1.0.0"
cat > src/counter.js <<'EOF'
export function count(items) { return items.length; }
export function sum(items) { return items.reduce((a, b) => a + b, 0); }
EOF
git add src/counter.js
git commit -q -m "feat: add sum()"
cat > src/counter.js <<'EOF'
export function count(items) { return Array.isArray(items) ? items.length : 0; }
export function sum(items) { return items.reduce((a, b) => a + b, 0); }
EOF
git add src/counter.js
git commit -q -m "fix: count() returns 0 for a non-array"
